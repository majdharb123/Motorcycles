class Product {
  final String id;
  final String name;
  final double price;
  final int star;
  final String description;
  final String engine;
  final int power;
  final int topSpeed;
  final int fuel;
  final int weight;
  final int mileage;
  final String image;

  Product({
    required this.id,
    required this.name,
    required this.price,
    required this.star,
    required this.description,
    required this.engine,
    required this.power,
    required this.topSpeed,
    required this.fuel,
    required this.weight,
    required this.mileage,
    required this.image,
  });
}
